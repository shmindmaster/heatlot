#!/usr/bin/env node
/**
 * npm run docs:reference — generate the developer reference from the code. Never edit the outputs.
 *
 *   mcp-servers/kestrel-foundry-data/catalog.json   the live tools/list result, from a real client
 *   docs/reference/mcp-tools.md                     tool reference rendered from that catalog
 *   docs/reference/decision-schemas.md              typed-decision reference rendered from schemas/
 *                                                   and from what each provider adapter derives
 *
 * `--check` regenerates in memory and fails if a committed file differs, so the reference cannot
 * drift from the server or the schemas. Deterministic: sorted keys and lists, no timestamps.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { Client } from '@modelcontextprotocol/client';
import { StdioClientTransport } from '@modelcontextprotocol/client/stdio';

import { listDecisions } from '../src/decisions/registry.mjs';
import { toStrictTool } from '../src/providers/anthropic.mjs';
import { isOpenAICompliant, toStructuredOutput } from '../src/providers/openai.mjs';

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SERVERS = [
  { name: 'heatlot', md: 'heatlot-mcp-tools.md',
    summary: (n) => `${n} tools over the receiving queue. They call the HTTP API's routes in process, so the MCP and HTTP contracts are one. \`packets.inspect\` appends signed receipts and is the only tool that writes; there is no release tool, because release is an inspector's decision.` },
  { name: 'kestrel-foundry-data', md: 'mcp-tools.md',
    summary: (n) => `All ${n} tools are read-only lookups over the synthetic Kestrel Castings dataset (the original foundry example).` },
].map((s) => ({ ...s, server: path.join(REPO_ROOT, 'mcp-servers', s.name, 'src', 'server.mjs'), catalog: path.join(REPO_ROOT, 'mcp-servers', s.name, 'catalog.json'), tools: path.join(REPO_ROOT, 'docs', 'reference', s.md) }));
const OUT = { decisions: path.join(REPO_ROOT, 'docs', 'reference', 'decision-schemas.md') };
const slug = (text) => text.toLowerCase().replace(/[^a-z0-9 _-]/g, '').replace(/ /g, '-');
const rel = (p) => path.relative(REPO_ROOT, p).split(path.sep).join('/');

function sortKeys(value) {
  if (Array.isArray(value)) return value.map(sortKeys);
  if (value && typeof value === 'object') return Object.fromEntries(Object.keys(value).sort().map((k) => [k, sortKeys(value[k])]));
  return value;
}

async function catalog(srv) {
  const client = new Client({ name: 'heatlot-reference-docs', version: '1' }, { versionNegotiation: { mode: 'auto' } });
  await client.connect(new StdioClientTransport({ command: process.execPath, args: [srv.server], stderr: 'ignore' }));
  try {
    const listed = await client.listTools();
    const { tools } = listed;
    return {
      server: srv.name,
      protocolRevision: client.getNegotiatedProtocolVersion(),
      cache: { ttlMs: listed.ttlMs, cacheScope: listed.cacheScope },
      tools: tools.map((t) => sortKeys(t)).sort((a, b) => a.name.localeCompare(b.name)),
    };
  } finally {
    await client.close();
  }
}

function typeOf(schema) {
  if (!schema || typeof schema !== 'object') return 'any';
  if (schema.enum) return schema.enum.map((v) => `\`${JSON.stringify(v)}\``).join(' \\| ');
  if (schema.const !== undefined) return `\`${JSON.stringify(schema.const)}\``;
  if (Array.isArray(schema.type)) return schema.type.join(' \\| ');
  if (schema.type === 'array') return `array of ${typeOf(schema.items)}`;
  if (schema.anyOf) return schema.anyOf.map(typeOf).join(' \\| ');
  return schema.type ?? 'object';
}

function constraints(schema) {
  const out = [];
  for (const key of ['pattern', 'minimum', 'maximum', 'minLength', 'maxLength', 'minItems', 'maxItems', 'format']) {
    if (schema?.[key] !== undefined) out.push(`${key} ${key === 'pattern' ? `\`${schema[key]}\`` : schema[key]}`);
  }
  return out.join(', ');
}

function fieldTable(schema) {
  const props = schema?.properties ?? {};
  const required = new Set(schema?.required ?? []);
  const names = Object.keys(props).sort();
  if (names.length === 0) return '_No fields._\n';
  const rows = names.map((n) => `| \`${n}\` | ${typeOf(props[n])} | ${required.has(n) ? 'yes' : 'no'} | ${constraints(props[n]) || '—'} |`);
  return ['| Field | Type | Required | Constraints |', '|---|---|---|---|', ...rows, ''].join('\n');
}

function toolsMarkdown(cat, srv) {
  const lines = [
    `# MCP tool reference: ${srv.name}`,
    '',
    `Generated by \`npm run docs:reference\` from the live \`tools/list\` result (\`${rel(srv.catalog)}\`). Do not edit by hand; CI fails if this file drifts from the server.`,
    '',
    `Protocol revision negotiated: **${cat.protocolRevision}**. The server also serves the 2025-era handshake (dual era), over stdio by default or over Streamable HTTP on 127.0.0.1 with \`--http [port]\`.`,
    '',
    `${srv.summary(cat.tools.length)} Each returns typed \`structuredContent\` that conforms to its output schema. Inputs are strict: an unknown argument is refused, not dropped.`,
    '',
    `\`tools/list\` is cacheable for ${cat.cache.ttlMs / 60000} minutes (\`cacheScope: ${cat.cache.cacheScope}\`): the catalogue is fixed for a release and holds no tenant data.`,
    '',
    '| Tool | Title | Read-only | Idempotent | Destructive | Open world |',
    '|---|---|---|---|---|---|',
    ...cat.tools.map((t) => `| [\`${t.name}\`](#${slug(t.name)}) | ${t.title ?? '—'} | ${t.annotations?.readOnlyHint} | ${t.annotations?.idempotentHint} | ${t.annotations?.destructiveHint} | ${t.annotations?.openWorldHint} |`),
    '',
  ];
  for (const t of cat.tools) {
    lines.push(`## ${t.name}`, '', `**${t.title ?? t.name}.** ${t.description ?? ''}`, '', '**Input**', '', fieldTable(t.inputSchema), '**Output**', '', fieldTable(t.outputSchema));
  }
  return `${lines.join('\n').trimEnd()}\n`;
}

function decisionsMarkdown() {
  const decisions = listDecisions().slice().sort((a, b) => a.id.localeCompare(b.id));
  const lines = [
    '# Typed decision reference',
    '',
    'Generated by `npm run docs:reference` from `schemas/` (JSON Schema 2020-12) and the provider adapters. Do not edit by hand; CI fails if this file drifts.',
    '',
    'Each decision has one canonical schema. The Anthropic adapter derives a strict tool from it, the OpenAI adapter derives a structured output, and every result is validated against the canonical schema with Ajv before use.',
    '',
    '| Decision | Owning agent | Schema | Anthropic strict tool drops | OpenAI structured outputs |',
    '|---|---|---|---|---|',
  ];
  for (const d of decisions) {
    const dropped = toStrictTool(d.schema, { name: d.id })._dropped;
    let openai;
    try {
      const verdict = isOpenAICompliant(toStructuredOutput(d.schema, { name: d.id }).json_schema.schema);
      openai = verdict.ok ? 'compliant' : `not compliant (${verdict.issues.length} issues)`;
    } catch (e) {
      openai = `not derivable (${e.message})`;
    }
    lines.push(`| \`${d.id}\` | \`${d.agent}\` | \`${d.schemaFile}\` | ${dropped.length ? dropped.map((k) => `\`${k}\``).join(', ') : 'nothing'} | ${openai} |`);
  }
  lines.push('');
  for (const d of decisions) {
    lines.push(`## ${d.id}`, '', `**${d.schema.title ?? d.id}.** ${(d.schema.description ?? '').replace(/\s+/g, ' ').trim()}`, '', fieldTable(d.schema));
  }
  return `${lines.join('\n').trimEnd()}\n`;
}

async function main() {
  const check = process.argv.includes('--check');
  const outputs = [[OUT.decisions, decisionsMarkdown()]];
  for (const srv of SERVERS) {
    const cat = await catalog(srv);
    outputs.push([srv.catalog, `${JSON.stringify(cat, null, 2)}\n`], [srv.tools, toolsMarkdown(cat, srv)]);
  }
  const stale = [];
  for (const [file, content] of outputs) {
    if (check) {
      let current = null;
      try { current = readFileSync(file, 'utf8').replace(/\r\n/g, '\n'); } catch { /* missing */ }
      if (current !== content) stale.push(rel(file));
    } else {
      mkdirSync(path.dirname(file), { recursive: true });
      writeFileSync(file, content);
      console.log(`wrote ${rel(file)}`);
    }
  }
  if (check) {
    if (stale.length) {
      console.error(`reference docs are stale: ${stale.join(', ')}. Run npm run docs:reference and commit.`);
      process.exit(1);
    }
    console.log('reference docs match the server and the schemas');
  }
}

main().catch((error) => { console.error(`docs:reference failed: ${error.message}`); process.exit(1); });
